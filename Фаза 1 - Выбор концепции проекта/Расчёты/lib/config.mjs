// Группы попарных сравнений МАИ: сначала критерии, затем альтернативы по каждому критерию.
export function ahpGroups() {
  const groups = [{ id: 'criteria', title: 'Важность критериев', items: CRITERIA.map((c) => c.id) }];
  for (const c of CRITERIA) {
    groups.push({ id: c.id, title: `Альтернативы по ${c.id}`, items: ALTERNATIVES.map((a) => a.id) });
  }
  return groups;
}

export function pairsOf(items) {
  const pairs = [];
  for (let i = 0; i < items.length; i++) {
    for (let j = i + 1; j < items.length; j++) pairs.push([items[i], items[j]]);
  }
  return pairs;
}

